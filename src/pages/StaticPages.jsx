/* =============== تواصل معنا =============== */

export function Contact() {
  const { user, profile } = useAuth();
  const [name, setName] = useState(profile?.name || "");
  const [email, setEmail] = useState(user?.email || "");
  const [text, setText] = useState("");
  const [sent, setSent] = useState(false);
  const [sending, setSending] = useState(false);
  const [error, setError] = useState("");

  async function handleSubmit(e) {
    e.preventDefault();
    if (!text.trim()) return;
    setSending(true);
    setError("");
    try {
      await sendContactMessage({
        name,
        email,
        text: text.trim(),
        uid: user?.uid,
      });
      setSent(true);
      setText("");
    } catch (err) {
      setError("تعذر إرسال الرسالة، حاول مرة أخرى.");
    } finally {
      setSending(false);
    }
  }

  return (
    <Page
      title="تواصل معنا"
      subtitle="لأي استفسار أو طلب توثيق كتاجر معتمد"
    >
      <Section title="ابعتلنا رسالة">
        <Para>
          ابعتلنا استفسارك أو طلب التوثيق، وهيتم الرد عليك من إدارة الموقع
          في أقرب وقت.
        </Para>

        {sent ? (
          <div
            style={{
              background: "var(--kabbash-light)",
              border: "1px solid var(--kabbash)",
              color: "var(--kabbash)",
              padding: "12px 16px",
              borderRadius: 10,
              fontSize: 13.5,
              fontWeight: 700,
              marginTop: 10,
            }}
          >
            ✅ تم إرسال رسالتك بنجاح، شكرًا لتواصلك معنا.
          </div>
        ) : (
          <form
            onSubmit={handleSubmit}
            style={{
              display: "flex",
              flexDirection: "column",
              gap: 10,
              maxWidth: 460,
              marginTop: 12,
            }}
          >
            <input
              className="input"
              type="text"
              placeholder="الاسم"
              value={name}
              onChange={(e) => setName(e.target.value)}
              required
            />
            <input
              className="input"
              type="email"
              placeholder="البريد الإلكتروني"
              value={email}
              onChange={(e) => setEmail(e.target.value)}
              required
            />
            <textarea
              className="input"
              placeholder="رسالتك"
              value={text}
              onChange={(e) => setText(e.target.value)}
              required
              rows={5}
              style={{ resize: "vertical", minHeight: 100 }}
            />
            <button
              className="btn btn-primary"
              type="submit"
              disabled={sending}
            >
              {sending ? "جاري الإرسال..." : "إرسال الرسالة"}
            </button>
            {error && (
              <p style={{ color: "var(--danger)", fontSize: 12.5 }}>
                {error}
              </p>
            )}
          </form>
        )}
      </Section>
    </Page>
  );
}

